docs["09-hybrid-rrf.md"] = """# 混合检索与 RRF 融合

混合检索同时执行向量检索与全文检索，再把两路结果融合成一个排序。向量路负责语义召回，能处理同义改写和跨语言表达；全文路负责精确匹配，能抓住专有名词、编号和罕见词。两路互补，整体召回通常高于任何单路。

融合算法里 RRF（Reciprocal Rank Fusion）最常用。它不看原始分数，只看名次：每个文档的得分是各路口径下 1 除以（常数 k 加名次）之和，k 通常取 60。这样做的好处是无需把余弦距离和 BM25 分数归一化到同一量纲，避免某一路因为分数量级大而压倒另一路。

RRF 的局限是丢弃了分数强弱，只保留相对顺序。如果某一路只有少量高质量结果，另一路有大量平庸结果，融合后的前列可能被平庸结果占据。改进方式包括加权 RRF、按分数归一化后线性组合，或者加一层交叉编码器重排。

关键工程要求是融合发生在数据库内部。应用层分别查两路再自己拼合，不仅多一次往返，还容易在分页、过滤和事务一致性上出错。seekdb 提供 DBMS_HYBRID_SEARCH，可以在一条 SQL 里完成两路召回与 RRF 排序。
"""

docs["10-chunking.md"] = """# 文档分块策略

分块是把长文档切成适合嵌入的小段。块太大，向量会混入多个主题，语义被平均掉；块太小，上下文不足，模型难以判断含义。中文技术文档常用三百到五百字符一块，相邻块保留五十到八十字符重叠，避免句子被切断后语义丢失。

分块要尊重结构。优先按标题、段落、列表切分，再按句号、问号、分号切句子，最后才做硬切。标题可以拼接到块首，给模型提供主题线索；列表项尽量保持完整。表格和代码块不宜从中间截断。

重叠不是越多越好。重叠区域会重复写入向量和全文索引，增加存储与检索噪声，也会让同一段内容在结果里出现多次。工程上要对重叠去重，或在结果聚合时按文档去重。

分块参数会显著影响评测结果。比较不同策略时，必须固定语料、查询集和嵌入模型，只改变分块参数，并同时报告块数量、平均长度、Recall@K 和端到端延迟。否则很难判断收益来自哪里。
"""


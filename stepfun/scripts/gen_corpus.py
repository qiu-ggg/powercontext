docs["21-batching-throughput.md"] = """# 批处理与推理吞吐

神经网络推理有固定的调度开销，单条处理会把大量时间花在启动和同步上。把多条文本组成一个批次送入模型，可以摊薄开销，显著提升吞吐。批大小受限于显存或内存、序列长度和运行时的内核实现。

批处理不是越大越好。批次增大后，单次延迟上升，首条结果要等整批算完；显存不足时会触发分配失败或回退。常见做法是按 token 总数而不是条数组批，把长文本单独处理，短文本合并。设置上限，例如每批不超过 32 条且总 token 不超过 8192。

交互式场景要平衡吞吐与响应。用户导入一百个块时，可以用大批次追求总时间；用户输入查询时，只有一条文本，批处理没有意义，应关注单条延迟和模型预热。流式进度反馈能让用户感知进展，减少等待焦虑。

测量吞吐时要报告每秒处理的文本数或 token 数，并注明批大小、序列长度分布和是否包含前后处理。只报告总耗时无法判断优化点。
"""

docs["22-index-refresh.md"] = """# 索引刷新与写入可见性

向量索引和全文索引都不是写完立刻完全可见。为了批量构建的效率，数据库会把新写入先放进内存结构或增量段，达到阈值或显式刷新后才合并进主索引。刷新之前，新文档可能检索不到，表现为“导入成功但搜不出来”。

刷新策略要在实时性和成本之间权衡。每批写入后刷新，数据立即可见，但刷新本身有开销，频繁调用会拖慢导入；全部写完再刷新一次，导入最快，但中途查询会漏数据。常见折中是按固定条数或时间窗口刷新，并在导入结束时强制刷新一次。

应用层要能验证可见性。导入完成后立即执行一次针对新内容的检索，确认命中；界面上显示“已刷新”和刷新耗时。如果刷新失败，要保留错误信息并允许重试，而不是静默吞掉。

删除和更新也会影响索引。更新通常实现为删除旧块再插入新块，中间存在短暂的不一致窗口。对一致性要求高的场景，可以用事务或版本字段过滤，避免读到半更新的数据。
"""


docs["04-embedding-similarity.md"] = """# 文本嵌入与相似度度量

文本嵌入把一段文字映射成固定维度的稠密向量，语义相近的文本在向量空间里距离更近。嵌入模型通常在对比学习目标下训练：正样本是同一句话的两种表达或查询与相关段落，负样本是随机搭配。训练好之后，向量就可以用于语义检索、聚类、去重和推荐。

常用相似度有三种。余弦相似度衡量夹角，取值在负一到一之间，对向量长度不敏感；内积同时考虑方向和长度，适合已经归一化的向量；欧氏距离衡量直线距离，数值越小越相似。seekdb 的向量索引支持 cosine、l2 和 inner_product 三种距离，建索引时声明，查询时必须保持一致。

归一化是容易被忽略的细节。如果文档向量做了 L2 归一化而查询向量没有，余弦距离仍然可用，但内积会失真。端侧应用最好在生成向量的同一处统一归一化，并把维度、距离度量、模型版本写进集合的元数据。

不同模型的向量空间不可混用。即使维度都是 512，bge 与 MiniLM 的坐标轴含义完全不同。切换嵌入模型必须重建集合，否则检索结果会毫无意义。知识库的注册表要记录模型标识和维度，写入时校验。
"""

docs["05-hnsw-index.md"] = """# HNSW 向量索引原理

HNSW 即分层可导航小世界图，是目前主流的近似最近邻索引。它把向量组织成多层图：上层稀疏，用于快速跨越；下层稠密，用于精细搜索。查询从最高层的一个入口点开始，贪心地向距离更近的邻居移动，逐层下降，最后在底层做候选扩展。

建索引时有两个关键参数。M 控制每个节点的邻居数量，越大召回越高、内存越多；ef_construction 控制建图时的候选队列长度，越大图质量越好、构建越慢。查询时的 ef_search 决定候选队列大小，是召回与延迟之间最直接的旋钮。seekdb 的向量索引基于 vsag 库，建表时可以用 WITH 子句声明 distance、type 和 lib。

HNSW 是近似算法，不保证百分之百召回。对于小规模知识库，暴力扫描可能更快也更准；数据量到几万条以上，HNSW 的优势才明显。查询时如果不加 APPROXIMATE 关键字，部分数据库会走精确扫描，延迟随数据量线性增长。

增量写入会影响图结构。新向量插入后需要更新邻居关系，索引刷新之前，新数据可能检索不到。对实时性要求高的应用，要在写入批次结束后显式刷新索引，并把刷新耗时纳入性能统计。
"""

docs["06-quantization.md"] = """# 模型量化：INT8 与 FP16

量化用更低的数值精度表示权重和激活，换取更小的体积和更快的推理。FP16 把 32 位浮点截成 16 位，指数位保留，动态范围仍然很大，通常不需要校准数据，精度损失很小。INT8 把浮点映射到 8 位整数，需要为每个张量或每个通道计算缩放因子和零点，压缩比接近四倍。

以 bge-small-zh-v1.5 为例，FP32 模型约 94.9 MB，FP16 约 47.5 MB，压缩比约 2.0；INT8 约 23.9 MB，压缩比约 4.0。量化后的模型在 CPU 上还能利用整数指令和 SIMD，吞吐提升往往比体积收益更明显。代价是数值误差会改变向量方向，检索质量需要用 Recall@K、nDCG@K 这类指标实测，而不能只看演示效果。

静态量化用一批校准样本统计激活范围，动态量化在运行时计算范围。ONNX 生态里常用 onnxruntime 的 quantize_dynamic 生成 model_int8.onnx，权重为 INT8、部分算子保持浮点。浏览器端加载时，Transformers.js 通过 dtype 参数选择对应的模型文件。

选择策略通常是：WebGPU 用 FP16，兼顾显存和速度；WASM 用 INT8，兼顾体积和 CPU 吞吐；需要最高质量时用 FP32 作为基线。三种精度要在同一评测集上比较，记录质量变化幅度。
"""

docs["07-bm25-fulltext.md"] = """# BM25 与全文检索

BM25 是经典的词袋检索打分函数，综合考虑词频、逆文档频率和文档长度归一化。一个词在当前文档出现得越多，得分越高，但增益会饱和；一个词在整个语料里越罕见，区分度越高。文档越长，命中同样次数的得分会被惩罚，避免长文档天然占优。

BM25 依赖倒排索引：词典记录每个词出现在哪些文档、出现多少次、在哪些位置。查询时取出候选文档集合，累加各查询词的得分。它擅长精确术语、产品型号、人名地名和代码标识符，这些内容语义模型往往表示不好。

BM25 的弱点是词汇不匹配。用户问“怎么加快模型加载”，文档写的是“缩短冷启动时间”，两者没有共同词，全文检索就召回不到。反过来，语义向量检索能跨过字面差异，但对罕见专有名词可能不够敏感。这正是混合检索存在的理由。

中文全文检索还需要分词。按空格切分对中文无效，需要专门的分词器。常见方案有基于词典的 IK、基于字的 ngram，以及基于统计模型的分词。分词质量直接决定召回，停用词和标点处理也要考虑。
"""

